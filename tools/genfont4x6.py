#!/usr/bin/env python3
"""Generate the 4x6 font for MODE 1 on the VIC-II (MADS source).

Source: the X11 misc-fixed 4x6 font (src/fonts/4x6.bdf, contributed by
Janne V. Kujala, public domain; from xorg/font/misc-misc). Adapted: the
95 printable ASCII glyphs (32-126) as 8-byte glyphs in the REU font's
layout: rows 0-5 the font (each row in the high nybble, bit 7 the left
pixel: the engine draws the leftmost 4 bits of a row in MODE 1's 4-pixel
cells), rows 6-7 blank.
"""
import argparse


def parse(path):
    glyphs, enc, bbx, rows, inbits = {}, None, None, [], False
    ascent = 5
    for line in open(path):
        p = line.split()
        if not p:
            continue
        if p[0] == "FONT_ASCENT":
            ascent = int(p[1])
        elif p[0] == "ENCODING":
            enc = int(p[1])
        elif p[0] == "BBX":
            bbx = [int(v) for v in p[1:5]]
        elif p[0] == "BITMAP":
            rows, inbits = [], True
        elif p[0] == "ENDCHAR":
            inbits = False
            if enc is not None and 32 <= enc < 127:
                w, h, xo, yo = bbx
                g = [0] * 8
                top = ascent - (h + yo)
                for i, r in enumerate(rows):
                    y = top + i
                    v = int(r, 16) << (8 - len(r) * 4) if len(r) < 2 else int(r[:2], 16)
                    v >>= xo
                    if 0 <= y < 6:
                        g[y] = v & 0xF0
                glyphs[enc] = g
        elif inbits:
            rows.append(p[0])
    return glyphs


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("bdf")
    ap.add_argument("-o", "--output", required=True)
    a = ap.parse_args()
    g = parse(a.bdf)
    out = ["; Generated by tools/genfont4x6.py from src/fonts/4x6.bdf -- do not edit.",
           "; X11 misc-fixed 4x6 (Janne V. Kujala, public domain).",
           "font4x6:"]
    for c in range(32, 127):
        rows = g.get(c, [0] * 8)
        out.append("    dta " + ", ".join("$%02X" % b for b in rows) + "    ; %r" % chr(c))
    with open(a.output, "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
