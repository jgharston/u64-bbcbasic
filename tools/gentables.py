#!/usr/bin/env python3
"""Generate the MOS character tables (MADS source) for U64 BBC BASIC.

BBC BASIC speaks ASCII; the C64 KERNAL screen editor speaks PETSCII in the
lower/upper case character set. The MOS keeps the KERNAL editor and maps
between the two:

- ASCII letters: 'a'-'z' <-> PETSCII $41-$5A, 'A'-'Z' <-> PETSCII $C1-$DA.
- The eight ASCII characters the C64 lacks reuse PETSCII codes the C64
  keyboard can type, and the font glyph for each code is replaced:
      \\ = PETSCII $5C (pound key)      ^ = $5E (up-arrow key)
      _ = $5F (left-arrow key)          ` = $BA (Shift+@)
      { = $DB (Shift++)                 | = $A9 (Shift+pound)
      } = $DD (Shift+-)                 ~ = $DE (Shift+up-arrow)
- Keys without an ASCII meaning map to 0 (ignored).

Usage: gentables.py OUTPUT.s
"""
import sys

SPECIAL = {  # ASCII -> PETSCII for characters the C64 lacks
    0x5C: 0x5C, 0x5E: 0x5E, 0x5F: 0x5F, 0x60: 0xBA,
    0x7B: 0xDB, 0x7C: 0xA9, 0x7D: 0xDD, 0x7E: 0xDE,
}

GLYPHS = {  # ASCII -> 8 bytes, C64-style 2-pixel strokes
    0x5C: [0xC0, 0x60, 0x30, 0x18, 0x0C, 0x06, 0x03, 0x00],
    0x5E: [0x18, 0x3C, 0x66, 0x00, 0x00, 0x00, 0x00, 0x00],
    0x5F: [0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xFF],
    0x60: [0x30, 0x18, 0x0C, 0x00, 0x00, 0x00, 0x00, 0x00],
    0x7B: [0x0E, 0x18, 0x18, 0x70, 0x18, 0x18, 0x0E, 0x00],
    0x7C: [0x18, 0x18, 0x18, 0x18, 0x18, 0x18, 0x18, 0x00],
    0x7D: [0x70, 0x18, 0x18, 0x0E, 0x18, 0x18, 0x70, 0x00],
    0x7E: [0x00, 0x00, 0x76, 0xDC, 0x00, 0x00, 0x00, 0x00],
}

# PETSCII control keys -> BBC codes (as returned by GET/INKEY)
KEYS_IN = {
    0x0D: 13,    # RETURN
    0x14: 127,   # INST/DEL -> DELETE
    0x93: 12,    # Shift+CLR/HOME
    0x13: 30,    # HOME
    0x9D: 136,   # cursor left  (BBC *FX4,1 cursor codes)
    0x1D: 137,   # cursor right
    0x11: 138,   # cursor down
    0x91: 139,   # cursor up
}


def ascii_to_petscii(a):
    if a in SPECIAL:
        return SPECIAL[a]
    if 0x41 <= a <= 0x5A:
        return a + 0x80
    if 0x61 <= a <= 0x7A:
        return a - 0x20
    if 0x20 <= a <= 0x5D:
        return a
    return 0


def petscii_to_screen(p):
    if 0x40 <= p <= 0x5F:
        return p - 0x40
    if 0xA0 <= p <= 0xBF:
        return p - 0x40
    if 0xC0 <= p <= 0xDF:
        return p - 0x80
    return p  # $20-$3F


def rows(name, data, per=16):
    out = [name]
    for i in range(0, len(data), per):
        out.append("    dta " + ", ".join("$%02X" % b for b in data[i:i + per]))
    return out


def main():
    asc2pet = [ascii_to_petscii(a) for a in range(128)]
    pet2asc = [0] * 256
    for a in range(0x20, 0x7F):
        p = asc2pet[a]
        if p:
            assert pet2asc[p] == 0, "PETSCII %02X mapped twice" % p
            pet2asc[p] = a
    for p, a in KEYS_IN.items():
        pet2asc[p] = a
    # The KERNAL screen editor reads screen code $5E back as PETSCII $FF
    # (its pi special case), not $DE: both mean '~' here.
    pet2asc[0xFF] = 0x7E
    # screen codes as read back from the screen (OSBYTE &87), reverse off
    scr2asc = [0] * 128
    for p in range(256):
        if pet2asc[p] and 0x20 <= pet2asc[p] < 0x7F:
            s = petscii_to_screen(p)
            if s < 128:
                scr2asc[s] = pet2asc[p]

    lines = ["; Generated by tools/gentables.py -- do not edit", ""]
    lines += rows("asc2pet:", asc2pet) + [""]
    lines += rows("pet2asc:", pet2asc) + [""]
    lines += rows("scr2asc:", scr2asc) + [""]
    lines.append("; ASCII glyphs: screen code, 8 bytes; terminated by $FF")
    lines.append("glyphs:")
    for a, bits in sorted(GLYPHS.items()):
        s = petscii_to_screen(SPECIAL[a])
        lines.append("    dta $%02X, %s    ; %r" %
                     (s, ", ".join("$%02X" % b for b in bits), chr(a)))
    lines.append("    dta $FF")
    lines.append("")
    with open(sys.argv[1], "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
