#!/usr/bin/env python3
"""Generate the MOS maths tables (MADS source) for *TABLE (mathtab.s).

A quarter sine wave, 257 entries: round(sin(i * pi / 512) * 65536) for
i = 0..256, as low and high bytes (entry 256 is 65536: mathtab.s writes
it itself, the tables hold 0 there). *TABLE unfolds it by symmetry into
1024 32-bit values (docs/DESIGN_GRAPHICS.md section 4, option (a)).

Usage: genmath.py -o OUTPUT.s
"""
import argparse
import math


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", required=True)
    args = ap.parse_args()
    q = [round(math.sin(i * math.pi / 512) * 65536) for i in range(257)]
    assert q[256] == 65536 and all(v < 65536 for v in q[:256])
    q[256] = 0
    lines = ["; Generated by tools/genmath.py -- do not edit", ""]
    for name, part in (("sinq_lo", [v & 255 for v in q]),
                       ("sinq_hi", [v >> 8 for v in q])):
        lines.append(name + ":")
        for i in range(0, 257, 16):
            lines.append("    dta " + ", ".join("$%02X" % b for b in part[i:i + 16]))
    lines.append("")
    with open(args.o, "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
