#!/usr/bin/env python3
"""Build the user manual's chapters from templates and the *HELP texts.

docs/manual/src/*.md are the chapters as written by hand; a line

    @@help NAME [NAME ...]

in them is replaced by the *HELP entries of those names (from
src/help/help.txt, the same text the machine shows with *HELP), as
Markdown: a heading with the name and its aliases, the syntax lines as
a code block, the paragraphs as text ("U64:" paragraphs in bold). So the
manual's syntax and the machine's help cannot drift apart.

Checks: every name exists; every help entry except the generated lists
(KEYWORDS, COMMANDS, TOPICS) and HELP itself is used in some chapter, so
a new keyword or command cannot be left out of the manual.

    genmanual.py HELP.txt SRCDIR OUTDIR
"""
import os
import re
import sys

SKIP = {"KEYWORDS", "COMMANDS", "TOPICS", "HELP"}


def parse(path):
    entries, order, cur = {}, [], None
    for raw in open(path, encoding="ascii"):
        line = raw.rstrip("\n")
        if line.startswith("#"):
            continue
        if line.startswith("@@"):
            names = [x.strip().upper() for x in line[2:].split("|")]
            cur = [names, []]
            entries[names[0]] = cur
            order.append(names[0])
            continue
        if cur is not None:
            cur[1].append(line)
    return entries, order


def render(names, lines):
    """One help entry as Markdown."""
    aliases = [a for a in names[1:] if a.lstrip("*") != names[0].lstrip("*")]
    head = "`%s`" % names[0]
    if aliases:
        head += " (also " + ", ".join("`%s`" % a for a in aliases) + ")"
    out = ["#### " + head, ""]
    block, para = [], []

    def flush_para():
        if para:
            text = " ".join(para)
            if text.startswith("U64:"):
                text = "**U64:**" + text[4:]
            out.extend([text, ""])
            para.clear()

    def flush_block():
        if block:
            out.extend(["```"] + block + ["```", ""])
            block.clear()

    for line in lines:
        if line.startswith("  "):
            flush_para()
            block.append(line[2:])
        elif not line.strip():
            flush_para()
            flush_block()
        else:
            flush_block()
            para.append(line.strip())
    flush_para()
    flush_block()
    while out and not out[-1]:
        out.pop()
    return out


def main():
    helpfile, srcdir, outdir = sys.argv[1:4]
    entries, order = parse(helpfile)
    used = set()
    os.makedirs(outdir, exist_ok=True)
    for name in sorted(os.listdir(srcdir)):
        if not name.endswith(".md"):
            continue
        out = ["<!-- Generated by tools/genmanual.py from docs/manual/src/%s"
               " and src/help/help.txt: edit those, not this file. -->" % name, ""]
        for n, line in enumerate(open(os.path.join(srcdir, name), encoding="utf-8"), 1):
            line = line.rstrip("\n")
            m = re.match(r"^@@help\s+(.*)$", line)
            if not m:
                out.append(line)
                continue
            for key in m.group(1).split():
                key = key.upper()
                if key not in entries:
                    sys.exit("%s:%d: no help entry %s" % (name, n, key))
                used.add(key)
                out.extend(render(*entries[key]) + [""])
        while out and not out[-1]:
            out.pop()
        open(os.path.join(outdir, name), "w", encoding="utf-8").write("\n".join(out) + "\n")
    missing = [k for k in order if k not in used and k not in SKIP]
    if missing:
        sys.exit("help entries in no chapter: " + " ".join(missing))
    print("manual: %d entries in %d chapters" % (len(used), len([f for f in os.listdir(srcdir) if f.endswith('.md')])))


if __name__ == "__main__":
    main()
