#!/usr/bin/env python3
"""Write the keyword table for *LIST (src/mos/listcmd.s) as MADS source.

BBC BASIC 3.10's tokens $80-$FF and their keywords, from the interpreter
source (the table tools/bbctok.py reads, so *LIST and the PC tokeniser
agree): lt_lo/lt_hi, one pointer per token ($80-$FF) into lt_text, the
keywords with bit 7 set on their last character; tokens without a
keyword point at an empty entry (a single $80).

    tools/genlist.py -o build/gen/list_tokens.s
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bbctok  # noqa: E402


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("-o", required=True)
    a = ap.parse_args()
    text, offsets = [0x80], {}           # offset 0: the empty entry
    for tok in range(0x80, 0x100):
        kw = bbctok.DETOKEN.get(tok)
        if not kw:
            offsets[tok] = 0
            continue
        offsets[tok] = len(text)
        b = list(kw.encode("ascii"))
        b[-1] |= 0x80
        text += b
    lines = ["; Generated by tools/genlist.py: BBC BASIC 3.10 keywords for *LIST", ""]
    for label, op in (("lt_lo", "<"), ("lt_hi", ">")):
        lines.append(label)
        for i in range(0x80, 0x100, 8):
            lines.append("    dta " + ", ".join("%s[lt_text+%d]" % (op, offsets[t])
                                               for t in range(i, i + 8)))
    lines.append("lt_text")
    for i in range(0, len(text), 16):
        lines.append("    dta " + ", ".join("$%02X" % v for v in text[i:i + 16]))
    with open(a.o, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    sys.exit(main())
