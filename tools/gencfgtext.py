#!/usr/bin/env python3
"""The cartridge's built-in Ultimate settings (MADS source) for *SETUP and
the start-up check (ultctl.s): src/cfg/u64bbc.cfg as text with LF line
ends, the same file the build ships as u64bbc-*.cfg.

Usage: gencfgtext.py SRC.cfg -o OUTPUT.s
"""
import argparse


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("src")
    ap.add_argument("-o", required=True)
    args = ap.parse_args()
    text = "".join(l.rstrip("\r\n") + "\n" for l in open(args.src, encoding="ascii")
                   if l.strip())
    data = text.encode("ascii")
    lines = ["; Generated by tools/gencfgtext.py from %s -- do not edit" % args.src,
             "", "cfg_text:"]
    for i in range(0, len(data), 16):
        lines.append("    dta " + ", ".join("$%02X" % b for b in data[i:i + 16]))
    lines += ["CFG_LEN = %d" % len(data), ""]
    open(args.o, "w").write("\n".join(lines))


if __name__ == "__main__":
    main()
