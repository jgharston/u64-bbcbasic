#!/usr/bin/env python3
"""Generate the Upic line renderers (MADS source) for *UPIC SHOW.

Based on the Upic module of ultimate-uci-oscar64 (uii_upic_generate() in
include/ultimate_upic_lib.c, library 1.3.0), which ports Aleksi Eeben's
Upic v1.3 line renderer (per-line patched immediate operands, an exact
one-dot pixel pitch at 64 MHz) and Christian Gleissner's 48 MHz path (3 of
every 4 pixels shown). Adapted: generated at build time for the fixed
layout used here (byte column c at $1000 + c * 256, the nybble table at
--nyb), as MADS source; the same instructions in the same order, so the
library's calibrated delays (83 at 64 MHz, 52 at 48 MHz) apply.

Layout of one renderer (called with Y = picture row, page-aligned):
  0     patch list: 24 x lda col,y / sta site+1       (8 cycles each)
  144   ldx #delay / dex / bne *-1                     (5 cycles per count)
  149   pixels
  end   nop / nop / lda #0 / sta $d020 / rts
"""
import argparse

COLUMNS = 192


def column(c):
    return 0x1000 + c * 256


def generate(path, label, nyb, delay):
    patch = []          # (column address, site label)
    body = []
    for c in range(COLUMNS):
        col = column(c)
        if path == 48:
            if c & 1:
                body += ["    ldx $%04X,y" % col, "    stx $D020",
                         "    lda $%04X,x" % nyb, "    sta $D020"]
                continue
            if (c & 7) == 6:
                site = "s%d" % c
                body.append("%s lda #0" % site)
                patch.append((col, site))
            else:
                body.append("    lda $%04X,y" % col)
            body.append("    sta $D020")
        else:
            if (c & 7) == 7:
                site = "s%d" % c
                body.append("%s ldx #0" % site)
                patch.append((col, site))
            else:
                body.append("    ldx $%04X,y" % col)
            body += ["    stx $D020", "    lda $%04X,x" % nyb, "    sta $D020"]
    assert len(patch) == 24
    out = ["; Generated by tools/upic_gen.py -- do not edit.",
           "; Upic line renderer, %d MHz path. Based on ultimate-uci-oscar64's" % path,
           "; Upic module (Aleksi Eeben's Upic v1.3 renderer; 48 MHz path by",
           "; Christian Gleissner); see the tool for what was adapted.",
           "%s:" % label,
           "    .local %s_l" % label]
    for col, site in patch:
        out += ["    lda $%04X,y" % col, "    sta %s+1" % site]
    out += ["delay ldx #%d" % delay, "    dex", "    bne *-1"]
    out += body
    out += ["    nop", "    nop", "    lda #0", "    sta $D020", "    rts",
            "    .endl"]
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--path", type=int, choices=(48, 64), required=True)
    ap.add_argument("--label", required=True)
    ap.add_argument("--nyb", type=lambda s: int(s.replace("$", ""), 16), required=True)
    ap.add_argument("--delay", type=int)
    ap.add_argument("-o", "--output", required=True)
    a = ap.parse_args()
    delay = a.delay if a.delay is not None else (52 if a.path == 48 else 83)
    with open(a.output, "w") as f:
        f.write(generate(a.path, a.label, a.nyb, delay))


if __name__ == "__main__":
    main()
