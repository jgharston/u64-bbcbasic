#!/usr/bin/env python3
"""Generate a Upic Lite line renderer (MADS source).

Upic Lite: a live picture of 320 x 256 pixels, 1 or 2 bits per pixel,
every pixel exactly one dot wide (a 32-dot border left and right), drawn
by changing the border colour once per pixel, as Upic does.

The trick that makes it fit: $D020 uses only 4 bits, and the Ultimate's
palette is programmable. With the palette following bit 0 (2 colours) or
bits 0-1 (4 colours) of the colour index, the renderer writes shifted
copies of the picture byte straight to $D020:
- 1 bit:  lda col,y, then per pixel sta $d020 / lsr (6 cycles);
- 2 bits: ldx col,y / stx $d020, then lda shr2/4/6,x / sta $d020 (8
  cycles); every 4th byte load is an immediate operand patched before
  the line (Upic's trick), which brings the average under a dot.
At 64 MHz a dot is 7.875 CPU cycles (63 per 8 dots); the scheduler pads
(nop, bit zp) so store k lands in dot k. 48 MHz machines (5.875 cycles
per dot) can't do 1-dot pixels.

Byte layout: the leftmost pixel in the lowest bit(s).

Based on Upic by Aleksi Eeben (per-pixel border colour writes timed
against the beam at 64 MHz; patched immediate operands) and the line
renderer generator in ultimate-uci-oscar64's Upic module (Xander Mol,
include/ultimate_upic_lib.c). Adapted: palette-decoded packed pixels,
generated at build time as source.

    tools/upiclite_gen.py --bpp 2 --cols '$3000' --tables '$9000' \\
        --delay 140 --label ul_line -o renderer.s
"""
import argparse
import math
import sys

DOT = 63 / 8            # CPU cycles per dot at 64 MHz
WIDTH = 320


def schedule(bpp, n=WIDTH):
    """Store times (cycles, relative to store 0) and padding per pixel;
    the set of byte columns loaded as patched immediates."""
    imm = set(b for b in range(n * bpp // 8) if bpp == 2 and b % 4 == 3)
    times, pads = [0.0], [0]
    for k in range(1, n):
        lo, hi = k * DOT, (k + 1) * DOT
        if bpp == 1:
            sp = 6 + (4 if k % 8 == 0 else 0)
        else:
            sp = 8
            if k % 4 == 0:
                sp = (2 if k // 4 in imm else 4) + 4
        cand = times[-1] + sp
        pad = 0
        if cand < lo:
            pad = math.ceil(lo - cand)
            if pad == 1:
                pad = 2
            cand += pad
        if not lo <= cand < hi:
            raise SystemExit("no schedule: pixel %d at %.2f, window %.2f-%.2f"
                             % (k, cand, lo, hi))
        times.append(cand)
        pads.append(pad)
    return times, pads, imm


def padding(n):
    """Instructions taking exactly n cycles (n = 0 or >= 2)."""
    out = []
    while n >= 4 or n == 2:
        out.append("nop")
        n -= 2
    if n == 3:
        out.append("bit $ff")           # 3 cycles; flags are free here
        n = 0
    assert n == 0
    return out


def generate(bpp, cols, tables, delay, label):
    """Renderer source; tables: 1 bit none, 2 bits shr2/shr4/shr6 at
    tables, +$100, +$200 (b >> 2, 4, 6)."""
    times, pads, imm = schedule(bpp)
    body, patch = [], []
    for k in range(WIDTH):
        if bpp == 1:
            b, n = divmod(k, 8)
            if n == 0:
                body.append("    lda $%04X,y" % (cols + b * 256))
            body += ["    " + p for p in padding(pads[k])]
            body.append("    sta $D020")
            body.append("    lsr")         # always: the schedule counts it
        else:
            b, n = divmod(k, 4)
            if n == 0:
                if b in imm:
                    site = "%s_i%d" % (label, b)
                    body.append("%s:" % site)
                    body.append("    ldx #0")
                    patch.append("    lda $%04X,y" % (cols + b * 256))
                    patch.append("    sta %s+1" % site)
                else:
                    body.append("    ldx $%04X,y" % (cols + b * 256))
                body += ["    " + p for p in padding(pads[k])]
                body.append("    stx $D020")
            else:
                body.append("    lda $%04X,x" % (tables + (n - 1) * 256))
                body += ["    " + p for p in padding(pads[k])]
                body.append("    sta $D020")
    lines = [
        "; Generated by tools/upiclite_gen.py: Upic Lite line renderer,",
        "; %d bit%s per pixel, %d pixels of one dot. Y = row. Page-aligned:" % (
            bpp, "s" if bpp > 1 else "", WIDTH),
        "; the delay loop's branch must not cross a page.",
        "%s:" % label,
    ] + patch + [
        "    ldx #%d" % delay,
        "%s_dly:" % label,
        "    dex",
        "    bne %s_dly" % label,
    ] + body + [
        "    nop                         ; the last pixel keeps its dot",
        "    nop",
        "    lda #0",
        "    sta $D020",
        "    rts",
        "",
    ]
    return "\n".join(lines), times


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--bpp", type=int, choices=(1, 2), required=True)
    ap.add_argument("--cols", required=True, help="address of byte column 0")
    ap.add_argument("--tables", required=True, help="address of the tables")
    ap.add_argument("--delay", type=int, default=120)
    ap.add_argument("--label", default="ul_line")
    ap.add_argument("-o", "--output", required=True)
    a = ap.parse_args()
    num = lambda s: int(s.replace("$", "0x"), 0)
    src, times = generate(a.bpp, num(a.cols), num(a.tables), a.delay, a.label)
    with open(a.output, "w") as f:
        f.write(src)
    print("%s: last store at cycle %.0f of %.0f" % (a.output, times[-1], 384 * DOT))


if __name__ == "__main__":
    sys.exit(main())
