#!/usr/bin/env python3
"""Generate the sound engine's tables and default instruments (MADS source).

The octave of middle C in quarter semitones (BBC pitch 53-100; 53 =
middle C, 261.63 Hz; 89 = A 440 Hz) as SID frequency register values, for
PAL (985,248 Hz) and NTSC (1,022,727 Hz) clocks; the engine shifts it
per octave. And the
BBC's noise types: periodic noise at shift rate / 15 (a pulse tone) and
white noise at the shift rate (the SID's noise generator advances once
per 2^20 / freq clock cycles), for the BBC's shift rates 4 MHz / 512,
1024, 2048 (7812.5, 3906.25, 1953.125 Hz).

    tools/gensound.py -o build/gen/sound_tables.s --instruments build/gen/sound_inst.s
"""
import argparse
import sys

CLOCKS = {"pal": 985248, "ntsc": 1022727}
RATES = (7812.5, 3906.25, 1953.125)


def pitch_hz(p):
    return 261.6256 * 2 ** ((p - 53) / 48)


def reg(hz, clock):
    return min(0xFFFF, round(hz * (1 << 24) / clock))


def table(label, values):
    out = ["%s:" % label]
    for i in range(0, len(values), 16):
        out.append("    dta " + ", ".join("$%02X" % v for v in values[i:i + 16]))
    return out


# Default instruments (docs/DESIGN_SOUND.md section 9). Fields not given
# are 0. wave: control register bits ($10 tri, $20 saw, $40 pulse, $80
# noise, $04 ring, $02 sync); ad, sr: ADSR bytes; pw: 0-4095; pws: pulse
# sweep (rate, top, bottom); vib: (delay, width, rate); porta; filt: bit 0
# on + mode bits $10/$20/$40; res; cut: start, cuts: sweep (rate, top,
# bottom); fine; flags; waves/arps: tables (16 steps); speed; name.
INSTRUMENTS = [
    dict(name="SQUARE", wave=0x40, ad=0x09, sr=0xA8, pw=2048),
    dict(name="PIANO", wave=0x40, ad=0x0B, sr=0x00, pw=1536),
    dict(name="ORGAN", wave=0x50, ad=0x00, sr=0xF4, pw=2048),
    dict(name="STRINGS", wave=0x20, ad=0x88, sr=0xA9, vib=(20, 2, 6)),
    dict(name="BRASS", wave=0x20, ad=0x46, sr=0xA6, filt=0x11, res=6, cut=0x60,
         cuts=(2, 0xC0, 0x40), flags=2),
    dict(name="LEAD", wave=0x40, ad=0x05, sr=0xC6, pw=1024, pws=(8, 0x0E, 0x02),
         vib=(25, 3, 5)),
    dict(name="BASS", wave=0x20, ad=0x08, sr=0x48, filt=0x11, res=8, cut=0x28),
    dict(name="FLUTE", wave=0x10, ad=0x47, sr=0xA6, vib=(15, 2, 4)),
    dict(name="PLUCK", wave=0x40, ad=0x06, sr=0x00, pw=768),
    dict(name="BELL", wave=0x14, ad=0x0B, sr=0x0B),
    dict(name="KICK", wave=0x10, ad=0x08, sr=0x00, speed=1,
         waves=[0x81, 0x11, 0x11, 0x11, 0x11, 0x00],
         arps=[12, 0, 0xFB, 0xF6, 0xF1, 0]),
    dict(name="SNARE", wave=0x80, ad=0x08, sr=0x00, pw=2048, speed=1,
         waves=[0x81, 0x41, 0x81, 0x81, 0x00], arps=[0, 12, 0, 0, 0]),
    dict(name="HIHAT", wave=0x80, ad=0x04, sr=0x00),
    dict(name="PAD", wave=0x20, ad=0xA8, sr=0xCA, filt=0x11, res=10, cut=0x40,
         cuts=(1, 0xA0, 0x20)),
    dict(name="ARP", wave=0x40, ad=0x00, sr=0xF6, pw=2048, speed=2,
         waves=[0x41, 0x41, 0x41, 0xFF, 0x00], arps=[0, 4, 7, 0, 0]),
    dict(name="SYNC", wave=0x22, ad=0x05, sr=0xC6),
]


def instrument(d):
    r = bytearray(64)
    r[0] = d["wave"]
    r[1], r[2] = d["ad"], d["sr"]
    pw = d.get("pw", 0)
    r[3], r[4] = pw & 0xFF, pw >> 8
    r[5], r[6], r[7] = [v & 0xFF for v in d.get("pws", (0, 0, 0))]
    r[8], r[9], r[10] = d.get("vib", (0, 0, 0))
    r[11] = d.get("porta", 0)
    r[12], r[13], r[14] = d.get("filt", 0), d.get("res", 0), d.get("cut", 0)
    r[15], r[16], r[17] = [v & 0xFF for v in d.get("cuts", (0, 0, 0))]
    r[18], r[19] = d.get("fine", 0) & 0xFF, d.get("flags", 0)
    for i, w in enumerate(d.get("waves", [])):
        r[20 + i] = w
    for i, a in enumerate(d.get("arps", [])):
        r[36 + i] = a & 0xFF
    r[52] = d.get("speed", 0)
    name = d["name"].ljust(10)[:10].encode("ascii")
    r[53:63] = name
    r[63] = 0
    return r


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("-o", "--output", required=True)
    ap.add_argument("--instruments", required=True)
    a = ap.parse_args()
    lines = ["; Generated by tools/gensound.py: BBC pitch and noise tables for the SID"]
    for name, clock in CLOCKS.items():
        p = [reg(pitch_hz(53 + i), clock) for i in range(48)]
        n = [reg(r / 15, clock) for r in RATES] + \
            [min(0xFFFF, round(r * (1 << 20) / clock)) for r in RATES]
        lines += table("snd_f%s_lo" % name, [v & 0xFF for v in p])
        lines += table("snd_f%s_hi" % name, [v >> 8 for v in p])
        lines += table("snd_n%s_lo" % name, [v & 0xFF for v in n])
        lines += table("snd_n%s_hi" % name, [v >> 8 for v in n])
    data = b"".join(instrument(d) for d in INSTRUMENTS)
    inst = ["; Generated by tools/gensound.py: default instruments 1-16, 64 bytes each"]
    inst += table("snd_definst", list(data))
    with open(a.instruments, "w") as f:
        f.write("\n".join(inst) + "\n")
    with open(a.output, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    sys.exit(main())
